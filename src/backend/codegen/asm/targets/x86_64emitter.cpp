#include "includes/backend/codegen/asm/targets/x86_64emitter.h"

X86_64Emitter::X86_64Emitter(const FuncTable& funcTable) :
BaseEmitter(funcTable),
m_nextTempStackOffset(0),
m_nextVarStackOffset(0),
m_selectLabelCounter(0)
{ }

std::string X86_64Emitter::EmitHeader() const
{
    std::ostringstream header;

    // Comment header
    header << "================================================\n";
    header << "; Generated by picoC compiler\n";
    header << "; Target: x86_64 - NASM Intel Syntax\n";
    header << "================================================\n\n";

    header << "BITS 64\n";

    switch (TargetArchitecture::GetOS())
    {
        case OS::Linux:
            header << "default rel\n";
            header << "global _start\n";
            header << "extern main\n";
            header << "extern exit\n\n";
            break;

        case OS::Windows:
            header << "global mainCRTStartup\n";
            header << "extern main\n";
            header << "extern ExitProcess\n\n";
            break;

        default:
            break;
    }

    return header.str();
}

void X86_64Emitter::EmitPrologue(
    const IRFunction* func,
    int frameSize,
    std::ostream& out)
{
    // Push old base pointer and set new one.
    out << "    push rbp\n";
    out << "    mov rbp, rsp\n";

    // Calculate total frame = aligned frameSize
    int totalFrame = (frameSize + 15) & ~15;

    // Allocate stack space if needed
    if (totalFrame > 0)
    {
        out << "    sub rsp, " << totalFrame << "\n";
    }

    // Next temp slot starts right after the allocated locals (offset from rbp)
    this->m_nextTempStackOffset = totalFrame;

    // For addressing incoming args on Windows, we treat shadow-space as
    // existing; so set nextVar offset for Alloca is concidered as existing.
    if (TargetArchitecture::GetOS() == OS::Linux)
    {
        this->m_nextVarStackOffset = 0;
    }
    else if (TargetArchitecture::GetOS() == OS::Windows)
    {
        // We don't allocate the shadow space, but logically treat it as present
        // above saved RBP for computing argument addresses.
        this->m_nextVarStackOffset = WINDOWS_X64_SHADOW_SPACE;
    }

    out << "\n";
}

void X86_64Emitter::EmitEpilogue(std::ostream& out)
{
    out << "    mov rsp, rbp\n";  // Undo frame allocation.
    out << "    pop rbp\n";       // Restore old base pointer.
    out << "    ret\n";           // Return from function.
    this->m_valueToStackOffset.clear();
    this->m_nextTempStackOffset = 0;
    this->m_nextVarStackOffset = 0;
}

void X86_64Emitter::EmitInstruction(const IRInstruction* instr, std::ostream& out)
{
    // --- opcode ---
    auto opcode = instr->GetOpcode();

    // --- normal instruction operands ---
    const IRBaseValue* source1 = instr->GetNumOperands() >= SINGLE_OPERAND ? instr->GetOperand(SINGLE_OPERAND_INDEX) : nullptr;
    const IRBaseValue* source2 = instr->GetNumOperands() >= TWO_OPERANDS ? instr->GetOperand(TWO_OPERANDS_INDEX) : nullptr;
    const IRBaseValue* source3 = instr->GetNumOperands() >= THREE_OPERANDS ? instr->GetOperand(THREE_OPERANDS_INDEX) : nullptr;

    switch (opcode)
    {
        // -----------------------
        // Integer arithmetic
        // -----------------------
        case IROpcode::Add:
        case IROpcode::Sub:
        case IROpcode::Mul:
        case IROpcode::SDiv:
        case IROpcode::UDiv:
        case IROpcode::SRem:
        case IROpcode::URem:
        {
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n";

            switch (opcode)
            {
                case IROpcode::Add:
                    out << "    add rax, " << GetOperandAsm(source2, out) << "\n";
                    break;
                case IROpcode::Sub:
                    out << "    sub rax, " << GetOperandAsm(source2, out) << "\n";
                    break;
                case IROpcode::Mul:
                    out << "    imul rax, " << GetOperandAsm(source2, out) << "\n";
                    break;

                case IROpcode::SDiv:
                    out << "    cqo\n";
                    out << "    idiv " << GetOperandAsm(source2, out) << "\n";
                    break;

                case IROpcode::UDiv:
                    out << "    xor rdx, rdx\n";
                    out << "    div " << GetOperandAsm(source2, out) << "\n";
                    break;

                case IROpcode::SRem:
                    out << "    cqo\n";
                    out << "    idiv " << GetOperandAsm(source2, out) << "\n";
                    out << "    mov rax, rdx\n"; // remainder
                    break;

                case IROpcode::URem:
                    out << "    xor rdx, rdx\n";
                    out << "    div " << GetOperandAsm(source2, out) << "\n";
                    out << "    mov rax, rdx\n"; // remainder
                    break;

                default:
                    break;
            }

            out << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
            break;
        }

        // -----------------------
        // Bitwise
        // -----------------------
        case IROpcode::And:
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n"
                << "    and rax, " << GetOperandAsm(source2, out) << "\n"
                << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
                break;

        case IROpcode::Or:
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n"
                << "    or rax, " << GetOperandAsm(source2, out) << "\n"
                << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
                break;

        case IROpcode::Xor:
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n"
                << "    xor rax, " << GetOperandAsm(source2, out) << "\n"
                << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
                break;

        case IROpcode::Shl:
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n"
                << "    mov cl, " << GetOperandAsm(source2, out) << "\n"
                << "    shl rax, cl\n"
                << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
                break;

        case IROpcode::LShr:
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n"
                << "    mov cl, " << GetOperandAsm(source2, out) << "\n"
                << "    shr rax, cl\n"
                << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
                break;

        case IROpcode::AShr:
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n"
                << "    mov cl, " << GetOperandAsm(source2, out) << "\n"
                << "    sar rax, cl\n"
                << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
                break;

        // -----------------------
        // Integer comparisons
        // -----------------------
        case IROpcode::ICmpEq:
        case IROpcode::ICmpNe:
        case IROpcode::ICmpSlt:
        case IROpcode::ICmpSle:
        case IROpcode::ICmpSgt:
        case IROpcode::ICmpSge:
        case IROpcode::ICmpUlt:
        case IROpcode::ICmpUle:
        case IROpcode::ICmpUgt:
        case IROpcode::ICmpUge:
        {
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n";
            out << "    cmp rax, " << GetOperandAsm(source2, out) << "\n";

            const char* setInstr = "sete";
            switch (opcode)
            {
                case IROpcode::ICmpEq:
                    setInstr="sete";
                    break;
                case IROpcode::ICmpNe:
                    setInstr="setne";
                    break;
                case IROpcode::ICmpSlt:
                    setInstr="setl";
                    break;
                case IROpcode::ICmpSle:
                    setInstr="setle";
                    break;
                case IROpcode::ICmpSgt:
                    setInstr="setg";
                    break;
                case IROpcode::ICmpSge:
                    setInstr="setge";
                    break;
                case IROpcode::ICmpUlt:
                    setInstr="setb";
                    break;
                case IROpcode::ICmpUle:
                    setInstr="setbe"; 
                    break;
                case IROpcode::ICmpUgt:
                    setInstr="seta";
                    break;
                case IROpcode::ICmpUge:
                    setInstr="setae";
                    break;
                default:
                    break;
            }

            out << "    " << setInstr << " al\n"
                << "    movzx rax, al\n"
                << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
            break;
        }

        // -----------------------
        // Floating-point arithmetic (SSE)
        // -----------------------
        case IROpcode::FAdd:
        case IROpcode::FSub:
        case IROpcode::FMul:
        case IROpcode::FDiv:
        case IROpcode::FRem:
        {
            // Load operands into XMM registers (special float registers)
            LoadOperandAsFloat(source1, "xmm0", out);
            LoadOperandAsFloat(source2, "xmm1", out);

            switch (opcode)
            {
                case IROpcode::FAdd:
                    out << "    addsd xmm0, xmm1\n";
                    break;

                case IROpcode::FSub:
                    out << "    subsd xmm0, xmm1\n";
                    break;

                case IROpcode::FMul:
                    out << "    mulsd xmm0, xmm1\n";
                    break;

                case IROpcode::FDiv:
                    out << "    divsd xmm0, xmm1\n";
                    break;

                case IROpcode::FRem:
                {
                    // xmm0 = a, xmm1 = b (already loaded)
                    out << "    divsd xmm0, xmm1\n";             // a / b
                    out << "    roundsd xmm0, xmm0, 1\n";        // floor(a/b)
                    out << "    mulsd xmm0, xmm1\n";             // floor(a/b) * b

                    // Load original a into xmm2
                    out << "    movsd xmm2, qword " << GetOperandAsm(source1, out) << "\n";

                    out << "    subsd xmm2, xmm0\n";
                    out << "    movsd qword " << GetOperandAsm(instr, out) << ", xmm2\n";
                    return;
                }
            }

            // Store result back
            out << "    movsd qword " << GetOperandAsm(instr, out) << ", xmm0\n";
            break;
        }

        // -----------------------
        // Floating-point comparisons
        // -----------------------
        case IROpcode::FCmpEq:
        case IROpcode::FCmpNe:
        case IROpcode::FCmpLt:
        case IROpcode::FCmpLe:
        case IROpcode::FCmpGt:
        case IROpcode::FCmpGe:
        {
            // Load operands as float
            LoadOperandAsFloat(source1, "xmm0", out);
            LoadOperandAsFloat(source2, "xmm1", out);

            // Compare
            out << "    ucomisd xmm0, xmm1\n";

            const char* setInstr = "sete";
            switch(opcode)
            {
                case IROpcode::FCmpEq:
                    setInstr="sete";
                    break;
                case IROpcode::FCmpNe:
                    setInstr="setne";
                    break;
                case IROpcode::FCmpLt:
                    setInstr="setb";
                    break;
                case IROpcode::FCmpLe:
                    setInstr="setbe";
                    break;
                case IROpcode::FCmpGt:
                    setInstr="seta";
                    break;
                case IROpcode::FCmpGe:
                    setInstr="setae";
                    break;
                default: break;
            }

            // Store boolean result (0 or 1)
            out << "    " << setInstr << " al\n";
            out << "    movzx rax, al\n";
            out << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
            break;
        }

        // -----------------------
        // Memory
        // -----------------------
        case IROpcode::Load:
        {
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n";
            out << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
            break;
        }

        case IROpcode::Store:
        {
            // Load value to store into rax
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n";
            out << "    mov " << GetOperandAsm(source2, out) << ", rax\n";
            break;
        }

        case IROpcode::Alloca:
        {
            // Allocate a new stack slot for new var
            int allocaOffset = this->m_nextVarStackOffset;
            this->m_nextVarStackOffset += STACK_SLOT_SIZE;
            this->m_valueToStackOffset[instr] = allocaOffset;
            break;
        }

        // -----------------------
        // Control flow
        // -----------------------
        case IROpcode::Br:
        {
            const auto& successors = instr->GetParent()->GetSuccessors();
            out << "    jmp ." << successors[0]->GetLabel() << "\n";
            break;
        }

        case IROpcode::CondBr:
        {
            const auto& successors = instr->GetParent()->GetSuccessors();
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n"
                << "    cmp rax, 0\n"
                << "    jne ." << successors[0]->GetLabel() << "\n"
                << "    jmp ." << successors[1]->GetLabel() << "\n";
            break;
        }

        case IROpcode::Ret:
            if(source1)
            {
                out << "    mov rax, " << GetOperandAsm(source1, out) << "\n";
            }
            out << "    jmp .func_epilogue\n";
            break;

        case IROpcode::Call:
        {
            auto callOperands = instr->GetOperands();
            int numCallOperands = static_cast<int>(callOperands.size());

            if (TargetArchitecture::GetOS() == OS::Linux)
            {
                // Stack alignment
                int extraArgs = numCallOperands > SIX_ARGUEMENTS ? numCallOperands - SIX_ARGUEMENTS : 0;
                if (extraArgs % 2 != 0) out << "    sub rsp, 8\n";

                // push extra args right to left
                for (int i = numCallOperands - 1; i >= SIX_ARGUEMENTS; --i)
                {
                    out << "    push " << GetOperandAsm(callOperands[i], out) << "\n";
                }

                // move register args
                for (int i = 0; i < std::min(SIX_ARGUEMENTS, numCallOperands); ++i)
                {
                    out << "    mov " << x86_64::linuxArgMapping[i]
                        << ", " << GetOperandAsm(callOperands[i], out) << "\n";
                }

                out << "    call " << instr->GetCalledFunction()->GetName() << "\n";
                out << "    mov " << GetOperandAsm(instr, out) << ", rax\n"; // Return value

                // Restoring alignment and removing the func extra args
                if (extraArgs > 0) out << "    add rsp, " << (extraArgs * STACK_SLOT_SIZE) << "\n";
                if (extraArgs % 2 != 0) out << "    add rsp, 8\n";
            }
            else if (TargetArchitecture::GetOS() == OS::Windows)
            {
                int extraArgs = numCallOperands > FOUR_ARGUEMENTS ? numCallOperands - FOUR_ARGUEMENTS : 0;
                int stackArgsSize = extraArgs * STACK_SLOT_SIZE;

                int total = WINDOWS_X64_SHADOW_SPACE + stackArgsSize;

                // Ensure 16-byte alignment at CALL
                if ((total % STACK_ALIGNMENT) != 0)
                {
                    total += STACK_SLOT_SIZE;
                }

                out << "    sub rsp, " << total << "\n";

                // Write stack args (right-to-left)
                for (int i = 0; i < extraArgs; ++i)
                {
                    int argIndex = FOUR_ARGUEMENTS + i;
                    int argOffset = WINDOWS_X64_SHADOW_SPACE + i * STACK_SLOT_SIZE;
                    out << "    mov qword [rsp + " << argOffset << "], "
                        << GetOperandAsm(callOperands[argIndex], out) << "\n";
                }

                // Register args
                for (int i = 0; i < std::min(FOUR_ARGUEMENTS, numCallOperands); ++i)
                {
                    out << "    mov " << x86_64::windowsArgMapping[i]
                        << ", " << GetOperandAsm(callOperands[i], out) << "\n";
                }

                out << "    call " << instr->GetCalledFunction()->GetName() << "\n";
                out << "    mov " << GetOperandAsm(instr, out) << ", rax\n";

                out << "    add rsp, " << total << "\n";
            }
            else
            {
                out << "    call " << instr->GetCalledFunction()->GetName() << "\n";
                out << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
            }
            break;
        }

        case IROpcode::Select:
        {
            std::string lblTrue = SelectLabelGenerator();
            std::string lblEnd = SelectLabelGenerator();
            out << "    mov rax, " << GetOperandAsm(source1, out) << "\n"
                << "    cmp rax, 0\n"
                << "    jne " << lblTrue << "\n"
                << "    mov rax, " << GetOperandAsm(source2, out) << "\n"
                << "    jmp " << lblEnd << "\n"
                << lblTrue << ":\n"
                << "    mov rax, " << GetOperandAsm(source3, out) << "\n"
                << lblEnd << ":\n"
                << "    mov " << GetOperandAsm(instr, out) << ", rax\n";
            break;
        }

        default:
            break;
    }
}

void X86_64Emitter::EmitStart(std::ostream& out)
{
    if (TargetArchitecture::GetOS() == OS::Linux)
    {
        out << "_start:\n";

        // Kernel enters with RSP % 16 == 8
        out << "    and rsp, -16\n";

        // call main()
        out << "    call main\n";

        // exit(main_return)
        out << "    mov rdi, rax\n";
        out << "    call exit\n";

        out << "    hlt\n";
    }
    else if (TargetArchitecture::GetOS() == OS::Windows)
    {
        out << "mainCRTStartup:\n";

        // Windows x64 ABI:
        // - Stack is 16-byte aligned before CALL
        // - 32 bytes of shadow space required
        out << "    sub rsp, 40\n"; // 32 shadow + 8 align

        // call main()
        out << "    call main\n";

        // ExitProcess with the return from main
        out << "    mov ecx, eax\n";
        out << "    call ExitProcess\n";

        out << "    hlt\n";
    }
}

std::string X86_64Emitter::GetSectionDirective(SectionType sectionType) const
{
    switch (sectionType)
    {
    case SectionType::TEXT:
        return "section .text";

    case SectionType::DATA:
        return "section .data";

    case SectionType::RODATA:
        // NASM uses .rdata on Windows, .rodata on ELF
        if (TargetArchitecture::GetOS() == OS::Windows) return "section .rdata";
        return "section .rodata";

    case SectionType::BSS:
        return "section .bss";

    default:
        return "";
    }
}

std::string X86_64Emitter::GetGlobalDirective(const std::string& symbol) const
{
    return "global " + symbol;
}

std::string X86_64Emitter::GetDataDirective(int bytes) const
{
    switch (bytes)
    {
    case 1: return "db";
    case 2: return "dw";
    case 4: return "dd";
    case 8: return "dq";
    default:
        // Fallback.
        return "db";
    }
}

std::string X86_64Emitter::GetReserveDirective(int bytes) const
{
    switch (bytes)
    {
    case 1:
        return "resb";
    case 2:
        return "resw";
    case 4:
        return "resd";
    case 8:
        return "resq";
    default:
        return "resb";
    }
}

std::string X86_64Emitter::GetOperandAsm(const IRBaseValue* operand, std::ostream& out)
{
    if (!operand) return "0";

    if (auto* intConst = dynamic_cast<const IRConstantInt*>(operand))
    {
        return std::to_string(intConst->GetValue());
    }
    else if (auto* floatConst = dynamic_cast<const IRConstantFloat*>(operand))
    {
        // allocate a slot once and write the constant there
        std::string slot = slotOfInstr(floatConst, out);
        double floatValue = floatConst->GetValue();   // 64-bit float
        uint64_t bits;
        std::memcpy(&bits, &floatValue, sizeof(double));
        out << "    mov qword " << slot << ", 0x" << std::hex << bits << std::dec << "\n";  // qword = 64-bit
        // return the slot
        return slot;
    }
    else if (auto* boolConst = dynamic_cast<const IRConstantBool*>(operand))
    {
        return std::to_string(boolConst->GetValue());
    }
    else if (auto* globalVar = dynamic_cast<const IRGlobalVariable*>(operand))
    {
        return globalVar->GetName();
    }
    else if (auto* argVal = dynamic_cast<const IRArgument*>(operand))
    {
        // find argument index in current func (0-based)
        size_t foundIndex = 0;
        for (auto& arg : this->m_currentFunc->GetArguments())
        {
            if (argVal == arg.get()) break;
            ++foundIndex;
        }

        if (TargetArchitecture::GetOS() == OS::Linux)
        {
            // first 6 args in registers RDI, RSI, RDX, RCX, R8, R9
            if (foundIndex < SIX_ARGUEMENTS)
            {
                return x86_64::linuxArgMapping[foundIndex];
            }
            else
            {
                // first stack-passed arg (7th argument, foundIndex==6) is at [rbp+16]
                // formula: offset = 8 * (foundIndex - 6)
                int stackOffset = FIRST_STACK_ARG_OFFSET_LINUX + STACK_SLOT_SIZE * static_cast<int>(foundIndex - SIX_ARGUEMENTS);
                return "[rbp+" + std::to_string(stackOffset) + "]";
            }
        }
        else if (TargetArchitecture::GetOS() == OS::Windows)
        {
            // first 4 args in RCX,RDX,R8,R9
            if (foundIndex < FOUR_ARGUEMENTS)
            {
                return x86_64::windowsArgMapping[foundIndex];
            }
            else
            {
                // On Windows the caller provides a 32-byte shadow area at entry.
                // After push rbp; mov rbp,rsp:
                // saved rbp: [rbp]
                // return addr: [rbp+8]
                // shadow space: [rbp+16 .. rbp+47]
                // first pushed arg (arg5, foundIndex==4) is at [rbp+48]
                // so offset = 48 + 8 * (foundIndex - 4)
                int stackOffset = FIRST_STACK_ARG_OFFSET_WINDOWS + STACK_SLOT_SIZE * static_cast<int>(foundIndex - FOUR_ARGUEMENTS);
                return "[rbp+" + std::to_string(stackOffset) + "]";
            }
        }
        else
        {
            return "";
        }
    }

    // otherwise it's a local / temp
    return slotOfInstr(operand, out);
}

std::string X86_64Emitter::slotOfInstr(const IRBaseValue* value, std::ostream& out)
{
    if (!value) return "";

    auto it = this->m_valueToStackOffset.find(value);
    if (it != this->m_valueToStackOffset.end()) // already assigned
    {
        return "[rbp-" + std::to_string(it->second) + "]";
    }

    out << "    sub rsp, 8\n"; // Grow frame.
    // allocate new stack slot
    size_t slotOffset = this->m_nextTempStackOffset;
    this->m_nextTempStackOffset += STACK_SLOT_SIZE;   // 8 bytes per slot 
    this->m_valueToStackOffset[value] = static_cast<int>(slotOffset);
    return "[rbp-" + std::to_string(slotOffset) + "]";
}

void X86_64Emitter::LoadOperandAsFloat(const IRBaseValue* operand, const std::string& xmmReg, std::ostream& out)
{
    // Float64 -> double precision (movsd)
    if (operand->GetType() == IRType::GetFloat64())
    {
        out << "    movsd " << xmmReg << ", qword " << GetOperandAsm(operand, out) << "\n";
    }
    // Integer -> convert 64-bit int to double
    else
    {
        out << "    mov rax, " << GetOperandAsm(operand, out) << "\n"; // 64-bit integer
        out << "    cvtsi2sd " << xmmReg << ", rax\n";                 // convert to double
    }
}

std::string X86_64Emitter::SelectLabelGenerator()
{
    int id = this->m_selectLabelCounter;
    this->m_selectLabelCounter++;
    return ".Lsel_" + std::to_string(id);
}
