X86_64Emitter::X86_64Emitter(const FuncTable& funcTable) :
X86BaseEmitter(funcTable)
{ }

void X86_64Emitter::EmitExtraBssContent(const IRModule& module, std::ostream& out) const
{
    if (!module.IsPrimaryModule()) return;
    out << "    heap_mem: resb 1048576\n";
    out << "    heap_cur: resq 1\n";
    out << "\n";
}

std::string X86_64Emitter::EmitHeader(const IRModule& module) const
{
    std::ostringstream header;

    // Comment header
    header << ";===============================================\n";
    header << "; Generated by picoC compiler\n";
    header << "; Target: x86_64 - NASM Intel Syntax\n";
    header << ";===============================================\n\n";

    header << "BITS 64\n";

    switch (TargetArchitecture::GetOS())
    {
        case OS::Linux:
            header << "default rel\n";
            if (module.IsPrimaryModule())
            {
                header << "global _start\n";
                header << "global main\n";
                header << "global heap_alloc\n\n";

                header << "extern memcpy\n";
            }
            header << "extern println\n";
            header << "extern println_bool\n";
            header << "extern println_str\n";
            header << "extern println_double\n";
            header << "extern println_char\n";
            header << "extern readln\n";
            header << "extern read_int\n";
            header << "extern read_double\n";
            header << "extern heap_alloc\n\n";

            header << "extern __println_bool_true\n";
            header << "extern __println_bool_false\n";
            header << "extern __println_newline\n";
            header << "extern __println_minus\n";
            header << "extern __println_dot\n\n";
            break;

        case OS::Windows:
            if (module.IsPrimaryModule())
            {
                header << "global mainCRTStartup\n";
                header << "global main\n";
                header << "global heap_alloc\n";
                header << "extern ExitProcess\n";
                header << "extern exit\n";
                header << "extern memcpy\n\n";
            }
            header << "extern println\n";
            header << "extern println_double\n";
            header << "extern println_str\n";
            header << "extern println_bool\n";
            header << "extern println_char\n";
            header << "extern readln\n";
            header << "extern read_int\n";
            header << "extern read_double\n";
            header << "extern heap_alloc\n\n";

            header << "extern __println_fmt_int\n";
            header << "extern __println_fmt_double\n";
            header << "extern __println_fmt_str\n";
            header << "extern __println_fmt_char\n";
            header << "extern __println_bool_true\n";
            header << "extern __println_bool_false\n\n";
            break;

        default:
            break;
    }

    return header.str();
}

void X86_64Emitter::EmitPrologue(
    const IRFunction* func,
    int frameSize,
    std::ostream& out)
{
    // Push old base pointer and set new one.
    out << "    push rbp\n";
    out << "    mov rbp, rsp\n";

    int numArgs = static_cast<int>(func->GetNumArguments());

    // Calculating temp variables
    int temporaryVarSize = func->CountTempVars() * x86_64::STACK_SLOT_SIZE;

    // On Linux, register arguments must be spilled into the local frame
    // (there is no caller-provided shadow space like on Windows).
    int argSpillSize = 0;
    if (TargetArchitecture::GetOS() == OS::Linux)
    {
        int regArgs = std::min(numArgs, x86_64::SIX_ARGUEMENTS);
        argSpillSize = regArgs * x86_64::STACK_SLOT_SIZE;
    }

    // The semantic analysis frame size may undercount when sibling scopes
    // reuse offsets, but the IR gives every variable its own alloca.
    // Use the actual alloca sizes (8-byte aligned) so temp slots never overlap var slots.
    int allocaFrameSize = 0;
    if (func->GetEntryBlock())
    {
        for (const auto& instr : func->GetEntryBlock()->GetInstructions())
        {
            if (instr->GetOpcode() == IROpcode::Alloca)
            {
                int sz = GetTypeSize(instr->GetType());
                if (sz <= 0) sz = x86_64::STACK_SLOT_SIZE;
                int allocSize = (sz + 7) & ~7;  // match Alloca emission
                allocaFrameSize += allocSize;
            }
        }
    }
    int actualFrameSize = std::max(frameSize, allocaFrameSize);

    // Calculate total frame = aligned frameSize
    int bufferedTempSize = (temporaryVarSize + argSpillSize + 15) & ~15;
    int bufferedFrameSize = (actualFrameSize + 15) & ~15;
    int totalFrame = (bufferedTempSize + bufferedFrameSize + 15) & ~15;
    if (TargetArchitecture::GetOS() == OS::Windows)
    {
        totalFrame += x86_64::WINDOWS_X64_SHADOW_SPACE;
    }

    // Allocate stack space if needed
    if (totalFrame > 0)
    {
        out << "    ; allocate " << totalFrame << " bytes for locals/temps\n";
        out << "    sub rsp, " << totalFrame << "\n";
    }

    // Next temp slot starts right after the allocated locals (offset from rbp)
    this->m_nextTempStackOffset = bufferedFrameSize + x86_64::STACK_SLOT_SIZE;
    this->m_nextVarStackOffset = x86_64::STACK_SLOT_SIZE;

    // ---------------------------------------------------------------
    // Spill register arguments to memory so they survive clobbers
    // (idiv overwrites rdx, function calls destroy all volatile regs).
    // ---------------------------------------------------------------
    if (TargetArchitecture::GetOS() == OS::Windows)
    {
        // Windows x64 ABI: the caller allocates 32 bytes of shadow space
        // right above the return address.  After `push rbp; mov rbp,rsp`:
        //   [rbp+16] = home slot for rcx  (arg 0)
        //   [rbp+24] = home slot for rdx  (arg 1)
        //   [rbp+32] = home slot for r8   (arg 2)
        //   [rbp+40] = home slot for r9   (arg 3)
        int regArgs = std::min(numArgs, x86_64::FOUR_ARGUEMENTS);
        if (regArgs > 0)
        {
            out << "    ; spill register arguments to shadow space\n";
        }
        for (int i = 0; i < regArgs; ++i)
        {
            int offset = 16 + i * x86_64::STACK_SLOT_SIZE;
            out << "    mov [rbp+" << offset << "], "
                << x86_64::windowsArgMapping[i] << "\n";
        }
    }
    else if (TargetArchitecture::GetOS() == OS::Linux)
    {
        // Linux SysV ABI: no shadow space â€” spill into the local frame.
        // Each register argument gets a dedicated slot tracked via
        // m_valueToStackOffset so GetOperandAsm resolves them normally.
        int regArgs = std::min(numArgs, x86_64::SIX_ARGUEMENTS);
        if (regArgs > 0)
        {
            out << "    ; spill register arguments to local stack slots\n";
        }
        for (int i = 0; i < regArgs; ++i)
        {
            const IRBaseValue* argValue = func->GetArguments()[i].get();
            int offset = this->m_nextTempStackOffset;
            this->m_nextTempStackOffset += x86_64::STACK_SLOT_SIZE;
            this->m_valueToStackOffset[argValue] = offset;
            out << "    mov [rbp-" << offset << "], "
                << x86_64::linuxArgMapping[i] << "\n";
        }
    }

    out << "\n";
}

void X86_64Emitter::EmitEpilogue(std::ostream& out)
{
    out << "    mov rsp, rbp\n";  // Undo frame allocation.
    out << "    pop rbp\n";       // Restore old base pointer.
    out << "    ret\n";           // Return from function.
    this->m_valueToStackOffset.clear();
    this->m_nextTempStackOffset = 0;
    this->m_nextVarStackOffset = 0;
}

void X86_64Emitter::EmitInstruction(const IRInstruction* instr, std::ostream& out)
{
    // --- opcode ---
    auto opcode = instr->GetOpcode();

    // --- normal instruction operands ---
    const IRBaseValue* source1 = instr->GetNumOperands() >= x86_common::SINGLE_OPERAND ? instr->GetOperand(x86_common::SINGLE_OPERAND_INDEX) : nullptr;
    const IRBaseValue* source2 = instr->GetNumOperands() >= x86_common::TWO_OPERANDS ? instr->GetOperand(x86_common::TWO_OPERANDS_INDEX) : nullptr;
    const IRBaseValue* source3 = instr->GetNumOperands() >= x86_common::THREE_OPERANDS ? instr->GetOperand(x86_common::THREE_OPERANDS_INDEX) : nullptr;

    std::string tempAsmValue;

    // General comment header for the emitted instruction block
    switch (opcode)
    {
        // -----------------------
        // Integer arithmetic
        // -----------------------
        case IROpcode::Add:
        case IROpcode::Sub:
        case IROpcode::Mul:
        case IROpcode::SDiv:
        case IROpcode::UDiv:
        case IROpcode::SRem:
        case IROpcode::URem:
        {
            out << "    ; Integer arithmetic operation\n";

            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";

            switch (opcode)
            {
                case IROpcode::Add:
                    out << "    ; add rax, operand\n";
                    tempAsmValue = GetOperandAsm(source2, out);
                    out << "    add rax, " << tempAsmValue << "\n";
                    break;
                case IROpcode::Sub:
                    out << "    ; sub rax, operand\n";
                    tempAsmValue = GetOperandAsm(source2, out);
                    out << "    sub rax, " << tempAsmValue << "\n";
                    break;
                case IROpcode::Mul:
                    out << "    ; signed multiply rax * operand -> rax\n";
                    tempAsmValue = GetOperandAsm(source2, out);
                    out << "    imul rax, " << tempAsmValue << "\n";
                    break;

                case IROpcode::SDiv:
                    out << "    ; signed divide rdx:rax / operand -> rax (quotient)\n";
                    out << "    cqo\n";
                    tempAsmValue = GetOperandAsm(source2, out);
                    // Memory operands need an explicit qword size to match cqo (64-bit)
                    if (!tempAsmValue.empty() && tempAsmValue[0] == '[')
                        out << "    idiv qword " << tempAsmValue << "\n";
                    else
                        out << "    idiv " << tempAsmValue << "\n";
                    break;

                case IROpcode::UDiv:
                    out << "    ; unsigned divide rax / operand -> rax (quotient)\n";
                    out << "    xor rdx, rdx\n";
                    tempAsmValue = GetOperandAsm(source2, out);
                    if (!tempAsmValue.empty() && tempAsmValue[0] == '[')
                        out << "    div qword " << tempAsmValue << "\n";
                    else
                        out << "    div " << tempAsmValue << "\n";
                    break;

                case IROpcode::SRem:
                    out << "    ; signed remainder in rdx\n";
                    out << "    cqo\n";
                    tempAsmValue = GetOperandAsm(source2, out);
                    if (!tempAsmValue.empty() && tempAsmValue[0] == '[')
                        out << "    idiv qword " << tempAsmValue << "\n";
                    else
                        out << "    idiv " << tempAsmValue << "\n";
                    out << "    mov rax, rdx\n"; // remainder
                    break;

                case IROpcode::URem:
                    out << "    ; unsigned remainder in rdx\n";
                    out << "    xor rdx, rdx\n";
                    tempAsmValue = GetOperandAsm(source2, out);
                    if (!tempAsmValue.empty() && tempAsmValue[0] == '[')
                        out << "    div qword " << tempAsmValue << "\n";
                    else
                        out << "    div " << tempAsmValue << "\n";
                    out << "    mov rax, rdx\n"; // remainder
                    break;

                default:
                    break;
            }

            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
            break;
        }

        // -----------------------
        // Bitwise
        // -----------------------
        case IROpcode::And:
            out << "    ; Bitwise AND\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(source2, out);
            out << "    and rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
                break;

        case IROpcode::Or:
            out << "    ; Bitwise OR\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(source2, out);
            out << "    or rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
                break;

        case IROpcode::Xor:
            out << "    ; Bitwise XOR\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(source2, out);
            out << "    xor rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
                break;

        case IROpcode::Shl:
            out << "    ; Logical shift left\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(source2, out);
            out << "    mov cl, " << tempAsmValue << "\n"
                << "    shl rax, cl\n";
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
                break;

        case IROpcode::LShr:
            out << "    ; Logical shift right\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(source2, out);
            out << "    mov cl, " << tempAsmValue << "\n"
                << "    shr rax, cl\n";
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
                break;

        case IROpcode::AShr:
            out << "    ; Arithmetic shift right (preserve sign)\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(source2, out);
            out << "    mov cl, " << tempAsmValue << "\n"
                << "    sar rax, cl\n";
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
                break;

        // -----------------------
        // Integer comparisons
        // -----------------------
        case IROpcode::ICmpEq:
        case IROpcode::ICmpNe:
        case IROpcode::ICmpSlt:
        case IROpcode::ICmpSle:
        case IROpcode::ICmpSgt:
        case IROpcode::ICmpSge:
        case IROpcode::ICmpUlt:
        case IROpcode::ICmpUle:
        case IROpcode::ICmpUgt:
        case IROpcode::ICmpUge:
        {
            out << "    ; Integer comparison -> boolean (0/1)\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(source2, out);
            out << "    cmp rax, " << tempAsmValue << "\n";

            const char* setInstr = GetSetccMnemonic(opcode);

            tempAsmValue = GetOperandAsm(instr, out);
            out << "    " << setInstr << " al\n"
                << "    movzx rax, al\n"
                << "    mov " << tempAsmValue << ", rax\n";
            break;
        }

        // -----------------------
        // Floating-point arithmetic (SSE)
        // -----------------------
        case IROpcode::FAdd:
        case IROpcode::FSub:
        case IROpcode::FMul:
        case IROpcode::FDiv:
        case IROpcode::FRem:
        {
            out << "    ; Floating-point (double) operation using XMM registers\n";
            // Load operands into XMM registers (special float registers)
            LoadOperandAsFloat(source1, "xmm0", out);
            LoadOperandAsFloat(source2, "xmm1", out);

            switch (opcode)
            {
                case IROpcode::FAdd:
                    out << "    addsd xmm0, xmm1\n";
                    break;

                case IROpcode::FSub:
                    out << "    subsd xmm0, xmm1\n";
                    break;

                case IROpcode::FMul:
                    out << "    mulsd xmm0, xmm1\n";
                    break;

                case IROpcode::FDiv:
                    out << "    divsd xmm0, xmm1\n";
                    break;

                case IROpcode::FRem:
                {
                    // xmm0 = a, xmm1 = b (already loaded)
                    out << "    ; floating-point remainder (a - floor(a/b)*b)\n";
                    out << "    divsd xmm0, xmm1\n";             // a / b
                    out << "    roundsd xmm0, xmm0, 1\n";        // floor(a/b)
                    out << "    mulsd xmm0, xmm1\n";             // floor(a/b) * b

                    // Load original a into xmm2
                    tempAsmValue = GetOperandAsm(source1, out);
                    out << "    movsd xmm2, qword " << tempAsmValue << "\n";

                    out << "    subsd xmm2, xmm0\n";
                    tempAsmValue = GetOperandAsm(instr, out);
                    out << "    movsd qword " << tempAsmValue << ", xmm2\n";
                    return;
                }
            }

            // Store result back
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    movsd qword " << tempAsmValue << ", xmm0\n";
            break;
        }

        // -----------------------
        // Floating-point comparisons
        // -----------------------
        case IROpcode::FCmpEq:
        case IROpcode::FCmpNe:
        case IROpcode::FCmpLt:
        case IROpcode::FCmpLe:
        case IROpcode::FCmpGt:
        case IROpcode::FCmpGe:
        {
            out << "    ; Floating-point comparison -> boolean (0/1)\n";
            // Load operands as float
            LoadOperandAsFloat(source1, "xmm0", out);
            LoadOperandAsFloat(source2, "xmm1", out);

            // Compare
            out << "    ucomisd xmm0, xmm1\n";

            const char* setInstr = GetSetccMnemonic(opcode);

            // Store boolean result (0 or 1)
            out << "    " << setInstr << " al\n";
            out << "    movzx rax, al\n";
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
            break;
        }

        // -----------------------
        // Memory
        // -----------------------
        case IROpcode::Load:
        {
            out << "    ; Load from memory into register/slot\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";
            if (source1 && dynamic_cast<const IRInstruction*>(source1) &&
                static_cast<const IRInstruction*>(source1)->GetOpcode() == IROpcode::GEP)
            {
                // GEP stores address in slot; load from that address with correct element size
                auto elemType = instr->GetType();
                if (elemType->GetKind() == IRTypeKind::Int8 || elemType->GetKind() == IRTypeKind::Int1)
                {
                    out << "    movzx rax, byte [rax]\n";
                }
                else if (elemType->GetKind() == IRTypeKind::Int32)
                {
                    out << "    mov eax, dword [rax]\n";
                }
                else if (elemType->GetKind() == IRTypeKind::Float32)
                {
                    out << "    movss xmm0, dword [rax]\n";
                    out << "    movq rax, xmm0\n";
                }
                else if (elemType->GetKind() == IRTypeKind::Float64)
                {
                    out << "    movsd xmm0, qword [rax]\n";
                    out << "    movq rax, xmm0\n";
                }
                else
                {
                    out << "    mov rax, [rax]\n";  // Int64, pointer
                }
            }
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
            break;
        }

        case IROpcode::Store:
        {
            out << "    ; Store value into memory\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";
            tempAsmValue = GetOperandAsm(source2, out);
            if (source2 && dynamic_cast<const IRInstruction*>(source2) &&
                static_cast<const IRInstruction*>(source2)->GetOpcode() == IROpcode::GEP)
            {
                out << "    mov rbx, " << tempAsmValue << "\n";  // rbx = address (GEP slot holds it directly)
                auto elemType = static_cast<const IRInstruction*>(source2)->GetType();
                if (elemType->GetKind() == IRTypeKind::Int8 || elemType->GetKind() == IRTypeKind::Int1)
                {
                    out << "    mov [rbx], al\n";
                }
                else if (elemType->GetKind() == IRTypeKind::Int32)
                {
                    out << "    mov [rbx], eax\n";
                }
                else if (elemType->GetKind() == IRTypeKind::Float32)
                {
                    out << "    movq xmm0, rax\n";
                    out << "    movss [rbx], xmm0\n";
                }
                else if (elemType->GetKind() == IRTypeKind::Float64)
                {
                    out << "    movq xmm0, rax\n";
                    out << "    movsd [rbx], xmm0\n";
                }
                else
                {
                    out << "    mov [rbx], rax\n";  // Int64, pointer
                }
            }
            else
            {
                out << "    mov " << tempAsmValue << ", rax\n";
            }
            break;
        }

        case IROpcode::Alloca:
        {
            int varSize = GetTypeSize(instr->GetType());
            if (varSize <= 0) varSize = x86_64::STACK_SLOT_SIZE;
            // Align allocation to 8 bytes so zero-init and GEP never overflow
            int allocSize = (varSize + 7) & ~7;
            int allocaOffset = this->m_nextVarStackOffset;
            this->m_nextVarStackOffset += allocSize;
            this->m_valueToStackOffset[instr] = allocaOffset;
            if (varSize > x86_64::STACK_SLOT_SIZE && instr->GetType()->GetKind() == IRTypeKind::Array)
            {
                out << "    ; Zero-initialize array (calloc-style)\n";
                out << "    xor eax, eax\n";
                for (int i = 0; i < allocSize; i += x86_64::STACK_SLOT_SIZE)
                {
                    out << "    mov [rbp-" << (allocaOffset + i) << "], rax\n";
                }
            }
            break;
        }

        case IROpcode::GEP:
        {
            // GEP(base, index): compute address of arr[index]
            // Stack: arr[0] at rbp-X, arr[1] at rbp-X-8, ... -> base - index*scale
            // Global: arr[0] at symbol, arr[1] at symbol+8, ... -> base + index*scale
            out << "    ; GEP: array index\n";
            tempAsmValue = GetOperandAsm(source1, out);  // base: [rbp-X] or [rel symbol]
            out << "    lea rax, " << tempAsmValue << "\n";  // rax = base address
            tempAsmValue = GetOperandAsm(source2, out);  // index
            out << "    mov rbx, " << tempAsmValue << "\n";
            int scale = GetTypeSize(instr->GetType());
            if (scale <= 0) scale = 1;
            out << "    imul rbx, " << scale << "\n";
            bool isGlobal = (dynamic_cast<const IRGlobalVariable*>(source1) != nullptr);
            if (isGlobal)
                out << "    add rax, rbx\n";  // global: base + index*scale
            else
                out << "    sub rax, rbx\n";  // stack: base - index*scale
            int slotOffset = this->m_nextTempStackOffset;
            this->m_nextTempStackOffset += x86_64::STACK_SLOT_SIZE;
            this->m_valueToStackOffset[instr] = slotOffset;
            out << "    mov [rbp-" << slotOffset << "], rax\n";
            break;
        }

        // -----------------------
        // Type conversion
        // -----------------------
        case IROpcode::FPToSI:
        {
            // load the double from its memory slot directly into xmm0
            // then convert to a signed 64-bit integer
            out << "    ; FPToSI: convert double to signed int\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    movsd xmm0, qword " << tempAsmValue << "\n";
            out << "    cvttsd2si rax, xmm0\n";
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
            break;
        }

        case IROpcode::SIToFP:
        {
            // load the integer into rax, convert to double in xmm0
            // then store the double bits back via memory
            out << "    ; SIToFP: convert signed int to double\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n";
            out << "    cvtsi2sd xmm0, rax\n";
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    movsd qword " << tempAsmValue << ", xmm0\n";
            break;
        }

        // -----------------------
        // Control flow
        // -----------------------
        case IROpcode::Br:
        {
            const auto& successors = instr->GetParent()->GetSuccessors();
            out << "    ; Unconditional branch\n";
            out << "    jmp " << this->m_currentFunc->GetName() << "." << successors[0]->GetLabel() << "\n";
            break;
        }

        case IROpcode::CondBr:
        {
            const auto& successors = instr->GetParent()->GetSuccessors();
            out << "    ; Conditional branch: if operand != 0 jump to true label\n";
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n"
                << "    cmp rax, 0\n"
                << "    jne " << this->m_currentFunc->GetName() << "." << successors[0]->GetLabel() << "\n"
                << "    jmp " << this->m_currentFunc->GetName() <<"." << successors[1]->GetLabel() << "\n";
            break;
        }

        case IROpcode::Ret:
            out << "    ; Return from function (jump to epilogue label)\n";
            if(source1)
            {
                tempAsmValue = GetOperandAsm(source1, out);
                out << "    mov rax, " << tempAsmValue << "\n";
            }
            out << "    jmp " << this->m_currentFunc->GetName() << ".func_epilogue\n";
            break;

        case IROpcode::Call:
        {
            out << "    ; Function call\n";
            auto callOperands = instr->GetOperands();
            int numCallOperands = static_cast<int>(callOperands.size());

            if (TargetArchitecture::GetOS() == OS::Linux)
            {
                out << "    ; Linux SysV calling convention handling\n";
                // Stack alignment
                int extraArgs = numCallOperands > x86_64::SIX_ARGUEMENTS ? numCallOperands - x86_64::SIX_ARGUEMENTS : 0;
                if (extraArgs % 2 != 0) out << "    sub rsp, 8\n";

                // push extra args right to left
                for (int i = numCallOperands - 1; i >= x86_64::SIX_ARGUEMENTS; --i)
                {
                    tempAsmValue = GetOperandAsm(callOperands[i], out);
                    auto* argInstr = dynamic_cast<const IRInstruction*>(callOperands[i]);
                    bool argIsAlloca = (argInstr && argInstr->GetOpcode() == IROpcode::Alloca);
                    if (argIsAlloca && tempAsmValue.front() == '[')
                    {
                        out << "    lea rax, " << tempAsmValue << "\n";
                        out << "    push rax\n";
                    }
                    else
                    {
                        out << "    push " << tempAsmValue << "\n";
                    }
                }

                // move register args
                for (int i = 0; i < std::min(x86_64::SIX_ARGUEMENTS, numCallOperands); ++i)
                {
                    std::string tempValue = GetOperandAsm(callOperands[i], out);
                    auto* opInstr = dynamic_cast<const IRInstruction*>(callOperands[i]);
                    bool isAlloca = (opInstr && opInstr->GetOpcode() == IROpcode::Alloca);
                    if (isAlloca && tempValue.front() == '[')
                    {
                        out << "    lea " << x86_64::linuxArgMapping[i]
                            << ", " << tempValue << "\n";
                    }
                    else
                    {
                        out << "    mov " << x86_64::linuxArgMapping[i]
                            << ", " << tempValue << "\n";
                    }
                }

                out << "    call " << instr->GetCalledFunction()->GetName() << "\n";
                tempAsmValue = GetOperandAsm(instr, out);
                out << "    mov " << tempAsmValue << ", rax\n"; // Return value

                // Restoring alignment and removing the func extra args
                if (extraArgs > 0) out << "    add rsp, " << (extraArgs * x86_64::STACK_SLOT_SIZE) << "\n";
                if (extraArgs % 2 != 0) out << "    add rsp, 8\n";
            }
            else if (TargetArchitecture::GetOS() == OS::Windows)
            {
                out << "    ; Windows x64 calling convention handling (shadow space + register args)\n";
                int extraArgs = numCallOperands > x86_64::FOUR_ARGUEMENTS ? numCallOperands - x86_64::FOUR_ARGUEMENTS : 0;
                int stackArgsSize = extraArgs * x86_64::STACK_SLOT_SIZE;

                int total = x86_64::WINDOWS_X64_SHADOW_SPACE + stackArgsSize;

                // Ensure 16-byte alignment at CALL
                if ((total % x86_64::STACK_ALIGNMENT) != 0)
                {
                    total += x86_64::STACK_SLOT_SIZE;
                }

                out << "    sub rsp, " << total << "\n";

                // Write stack args (right-to-left)
                for (int i = 0; i < extraArgs; ++i)
                {
                    int argIndex = x86_64::FOUR_ARGUEMENTS + i;
                    int argOffset = i * x86_64::STACK_SLOT_SIZE;
                    tempAsmValue = GetOperandAsm(callOperands[argIndex], out);
                    auto* argInstr = dynamic_cast<const IRInstruction*>(callOperands[argIndex]);
                    bool argIsAlloca = (argInstr && argInstr->GetOpcode() == IROpcode::Alloca);
                    if (tempAsmValue.front() == '[')
                    {
                        if (argIsAlloca)
                            out << "    lea rax, " << tempAsmValue << "\n";
                        else
                            out << "    mov rax, " << tempAsmValue << "\n";
                        out << "    mov qword [rsp + " << argOffset << "], rax\n";
                    }
                    else
                    {
                        out << "    mov qword [rsp + " << argOffset << "], "
                            << tempAsmValue << "\n";
                    }
                }

                // Register args
                for (int i = 0; i < std::min(x86_64::FOUR_ARGUEMENTS, numCallOperands); ++i)
                {
                    std::string tempValue = GetOperandAsm(callOperands[i], out);
                    auto* opInstr = dynamic_cast<const IRInstruction*>(callOperands[i]);
                    bool isAlloca = (opInstr && opInstr->GetOpcode() == IROpcode::Alloca);
                    if (isAlloca && tempValue.front() == '[')
                    {
                        out << "    lea " << x86_64::windowsArgMapping[i]
                            << ", " << tempValue << "\n";
                    }
                    else
                    {
                        out << "    mov " << x86_64::windowsArgMapping[i]
                            << ", " << tempValue << "\n";
                    }
                }

                out << "    call " << instr->GetCalledFunction()->GetName() << "\n";
                tempAsmValue = GetOperandAsm(instr, out);
                out << "    mov " << tempAsmValue << ", rax\n";

                out << "    add rsp, " << total << "\n";
            }
            else
            {
                out << "    ; Generic call fallback\n";
                out << "    call " << instr->GetCalledFunction()->GetName() << "\n";
                tempAsmValue = GetOperandAsm(instr, out);
                out << "    mov " << tempAsmValue << ", rax\n";
            }
            break;
        }

        case IROpcode::Select:
        {
            out << "    ; Select (ternary) operator: choose between two values\n";
            std::string lblTrue = SelectLabelGenerator();
            std::string lblEnd = SelectLabelGenerator();
            tempAsmValue = GetOperandAsm(source1, out);
            out << "    mov rax, " << tempAsmValue << "\n"
                << "    cmp rax, 0\n"
                << "    jne " << lblTrue << "\n";
            // Condition false: use source3 (false value)
            tempAsmValue = GetOperandAsm(source3, out);
            out << "    mov rax, " << tempAsmValue << "\n"
                << "    jmp " << lblEnd << "\n"

                << lblTrue << ":\n";
            // Condition true: use source2 (true value)
            tempAsmValue = GetOperandAsm(source2, out);
            out << "    mov rax, " << tempAsmValue << "\n"
                
                << lblEnd << ":\n";
            tempAsmValue = GetOperandAsm(instr, out);
            out << "    mov " << tempAsmValue << ", rax\n";
            break;
        }

        default:
            out << "    ; (unhandled or no-op IR instruction)\n";
            break;
    }
}

void X86_64Emitter::EmitStart(const IRModule& module, std::ostream& out)
{
    if (!module.IsPrimaryModule()) return;

    if (TargetArchitecture::GetOS() == OS::Linux)
    {
        out << "_start:\n";
        out << "    and rsp, -16\n";

        for (const auto& [target, source] : module.GetDeferredGlobalInits())
        {
            out << "    mov rax, [rel " << source << "]\n";
            out << "    mov [rel " << target << "], rax\n";
        }

        out << "    call main\n";
        out << "    mov rdi, rax\n";
        out << "    mov rax, 60\n";
        out << "    syscall\n";
        out << "    hlt\n";

        out << "\n";
        out << "heap_alloc:\n";
        out << "    add rdi, 7\n";
        out << "    and rdi, -8\n";
        out << "    cmp qword [rel heap_cur], 0\n";
        out << "    jne .heap_alloc_no_init\n";
        out << "    lea rax, [rel heap_mem]\n";
        out << "    mov [rel heap_cur], rax\n";
        out << ".heap_alloc_no_init:\n";
        out << "    mov rax, [rel heap_cur]\n";
        out << "    mov rcx, rax\n";
        out << "    add rcx, rdi\n";
        out << "    mov [rel heap_cur], rcx\n";
        out << "    ret\n";
    }
    else if (TargetArchitecture::GetOS() == OS::Windows)
    {
        out << "mainCRTStartup:\n";
        out << "    sub rsp, 40\n";

        for (const auto& [target, source] : module.GetDeferredGlobalInits())
        {
            out << "    mov rax, [rel " << source << "]\n";
            out << "    mov [rel " << target << "], rax\n";
        }

        out << "    call main\n";
        out << "    mov ecx, eax\n";
        out << "    call exit\n";
        out << "    hlt\n";

        out << "\n";
        out << "heap_alloc:\n";
        out << "    add rcx, 7\n";
        out << "    and rcx, -8\n";
        out << "    cmp qword [rel heap_cur], 0\n";
        out << "    jne .heap_alloc_no_init\n";
        out << "    lea rax, [rel heap_mem]\n";
        out << "    mov [rel heap_cur], rax\n";
        out << ".heap_alloc_no_init:\n";
        out << "    mov rax, [rel heap_cur]\n";
        out << "    mov r10, rax\n";
        out << "    add r10, rcx\n";
        out << "    mov [rel heap_cur], r10\n";
        out << "    ret\n";
    }
}



std::string X86_64Emitter::GetGlobalDirective(const std::string& symbol) const
{
    return "global " + symbol;
}

std::string X86_64Emitter::GetOperandAsm(const IRBaseValue* operand, std::ostream& out)
{
    if (!operand) return "0";

    if (auto* intConst = dynamic_cast<const IRConstantInt*>(operand))
    {
        uint64_t bits = static_cast<uint64_t>(intConst->GetValue());
        out << "    mov r10, 0x" << std::hex << bits << std::dec << "\n";
        return "r10";
    }
    else if (auto* floatConst = dynamic_cast<const IRConstantFloat*>(operand))
    {
        // allocate a slot once and write the constant there
        std::string slot = slotOfInstr(floatConst, out);
        double floatValue = floatConst->GetValue();   // 64-bit float
        uint64_t bits;
        std::memcpy(&bits, &floatValue, sizeof(double));
        out << "    mov rax, 0x" << std::hex << bits << std::dec << "\n";
        out << "    mov " << slot << ", rax\n";
        // return the slot
        return slot;
    }
    else if (auto* strConst = dynamic_cast<const IRConstantString*>(operand))
    {
        // load effective address of the string label into r10
        out << "    lea r10, [rel " << strConst->GetLabel() << "]\n";
        return "r10";
    }
    else if (auto* boolConst = dynamic_cast<const IRConstantBool*>(operand))
    {
        uint64_t bits = static_cast<uint64_t>(boolConst->GetValue());  // 0 or 1
        out << "    mov r10, 0x" << std::hex << bits << std::dec << "\n";
        return "r10";
    }
    else if (auto* globalVar = dynamic_cast<const IRGlobalVariable*>(operand))
    {
        return "[rel " + globalVar->GetName() + "]";
    }
    else if (auto* argVal = dynamic_cast<const IRArgument*>(operand))
    {
        // find argument index in current func (0-based)
        size_t foundIndex = 0;
        for (auto& arg : this->m_currentFunc->GetArguments())
        {
            if (argVal == arg.get()) break;
            ++foundIndex;
        }

        if (TargetArchitecture::GetOS() == OS::Linux)
        {
            if (foundIndex < x86_64::SIX_ARGUEMENTS)
            {
                // Register arguments were spilled to local stack slots in
                // the prologue and recorded in m_valueToStackOffset.
                auto it = this->m_valueToStackOffset.find(argVal);
                if (it != this->m_valueToStackOffset.end())
                {
                    return "[rbp-" + std::to_string(it->second) + "]";
                }
            }

            // Stack-passed args (7th+): [rbp+16], [rbp+24], â€¦
            int stackOffset = x86_64::FIRST_STACK_ARG_OFFSET_LINUX + x86_64::STACK_SLOT_SIZE * static_cast<int>(foundIndex - x86_64::SIX_ARGUEMENTS);
            return "[rbp+" + std::to_string(stackOffset) + "]";
        }
        else if (TargetArchitecture::GetOS() == OS::Windows)
        {
            if (foundIndex < x86_64::FOUR_ARGUEMENTS)
            {
                // Register arguments were spilled to the caller's shadow
                // space in the prologue.  Read from there so we are safe
                // even after idiv / call clobber the volatile registers.
                //   [rbp+16] = arg 0,  [rbp+24] = arg 1, â€¦
                int offset = 16 + static_cast<int>(foundIndex) * x86_64::STACK_SLOT_SIZE;
                return "qword [rbp+" + std::to_string(offset) + "]";
            }
            else
            {
                // Stack-passed args (5th+): [rbp+48], [rbp+56], â€¦
                int stackOffset = x86_64::FIRST_STACK_ARG_OFFSET_WINDOWS + x86_64::STACK_SLOT_SIZE * static_cast<int>(foundIndex - x86_64::FOUR_ARGUEMENTS);
                return "[rbp+" + std::to_string(stackOffset) + "]";
            }
        }
        else
        {
            return "";
        }
    }

    // otherwise it's a local / temp
    return slotOfInstr(operand, out);
}

std::string X86_64Emitter::slotOfInstr(const IRBaseValue* value, std::ostream& out)
{
    if (!value) return "";

    auto it = this->m_valueToStackOffset.find(value);
    if (it != this->m_valueToStackOffset.end()) // already assigned
    {
        return "[rbp-" + std::to_string(it->second) + "]";
    }

    // allocate new stack slot
    int slotOffset = this->m_nextTempStackOffset;
    this->m_nextTempStackOffset += x86_64::STACK_SLOT_SIZE;   // 8 bytes per slot 
    this->m_valueToStackOffset[value] = slotOffset;
    return "[rbp-" + std::to_string(slotOffset) + "]";
}

void X86_64Emitter::LoadOperandAsFloat(const IRBaseValue* operand, const std::string& xmmReg, std::ostream& out)
{
    // Float64 -> double precision (movsd)
    if (operand->GetType() == IRType::GetFloat64())
    {
        std::string tempAsmValue = GetOperandAsm(operand, out);
        out << "    ; load double constant/slot into " << xmmReg << "\n";
        out << "    movsd " << xmmReg << ", qword " << tempAsmValue << "\n";
    }
    // Integer -> convert 64-bit int to double
    else
    {
        std::string tempAsmValue = GetOperandAsm(operand, out);
        out << "    ; convert 64-bit int to double in " << xmmReg << "\n";
        out << "    mov rax, " << tempAsmValue << "\n"; // 64-bit integer
        out << "    cvtsi2sd " << xmmReg << ", rax\n";                 // convert to double
    }
}

std::string X86_64Emitter::SelectLabelGenerator()
{
    int id = this->m_selectLabelCounter;
    this->m_selectLabelCounter++;
    return this->m_currentFunc->GetName() + ".Lsel_" + std::to_string(id);
}
