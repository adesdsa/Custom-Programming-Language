        out << "    cvtsi2sd xmm1, qword [rbp-24]\n";
        out << "    movsd xmm0, qword [rbp-8]\n";
        // Abs again in case of negative
        out << "    mov rax, 0x7FFFFFFFFFFFFFFF\n";
        out << "    mov [rbp-16], rax\n";
        out << "    andpd xmm0, [rbp-16]\n";
        out << "    subsd xmm0, xmm1\n";
