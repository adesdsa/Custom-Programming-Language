std::string X86_Emitter::GetDataDirective(int bytes)
{
    switch (bytes)
    {
        case 1:  return "db";
        case 2:  return "dw";
        case 4:  return "dd";
        case 8:  return "dq";
        default: return "db";  // fallback
    }
}

std::string X86_Emitter::GetReserveDirective(int bytes)
{
    switch (bytes)
    {
        case 1:  return "resb";
        case 2:  return "resw";
        case 4:  return "resd";
        case 8:  return "resq";
        default: return "resb";  // fallback
    }
}
