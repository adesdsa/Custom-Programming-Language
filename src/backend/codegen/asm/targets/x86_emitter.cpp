X86_Emitter::X86_Emitter(const FuncTable& funcTable) : 
    X86BaseEmitter(funcTable)
{}

std::string X86_Emitter::EmitHeader() const
{
    std::ostringstream header;

    // picoC signature
    header << "; Generated by picoC compiler\n";

    switch (TargetArchitecture::GetOS())
    {
        case OS::Linux:
            header << "; Target: x86 Linux (32-bit)\n\n";
            header << "BITS 32\n";
            header << "global _start\n";
            header << "extern main\n\n";

            header << "section .data\n";
            header << "    __println_bool_true db \"true\", 10, 0\n";
            header << "    __println_bool_false db \"false\", 10, 0\n\n";
            break;

        case OS::Windows:
            header << "; Target: x86 Windows (32-bit)\n\n";
            header << "BITS 32\n";
            header << "global _mainCRTStartup\n";
            header << "extern _main\n";
            header << "extern _ExitProcess@4\n";
            header << "extern _printf\n";
            header << "extern _exit\n\n";

            // built-in format strings (used by println and other built-ins)
            header << "section .data\n";
            header << "    __println_fmt_int db \"%d\", 10, 0\n";
            header << "    __println_fmt_double db \"%g\", 10, 0\n";
            header << "    __println_fmt_str db \"%s\", 10, 0\n";
            header << "    __println_bool_true db \"true\", 0\n";
            header << "    __println_bool_false db \"false\", 0\n\n";
            break;

        default:
            break;
    }

    return header.str();
}

void X86_Emitter::EmitPrologue(const IRFunction* func, int frameSize, std::ostream& out)
{
    // The semantic analysis frame size may undercount when sibling scopes
    // reuse offsets, but the IR gives every variable its own alloca.
    // Use the actual alloca count so temp slots never overlap var slots.
    int numAllocas = 0;
    if (func->GetEntryBlock())
    {
        for (const auto& instr : func->GetEntryBlock()->GetInstructions())
        {
            if (instr->GetOpcode() == IROpcode::Alloca) numAllocas++;
        }
    }
    int allocaFrameSize = numAllocas * x86_32::STACK_SLOT_SIZE;
    int actualFrameSize = std::max(frameSize, allocaFrameSize);

    // reset stack tracking for this function
    this->m_nextVarStackOffset = x86_32::STACK_SLOT_SIZE;  // start after saved ebp
    this->m_nextTempStackOffset = actualFrameSize + x86_32::STACK_SLOT_SIZE;
    this->m_valueToStackOffset.clear();

    // save caller's base pointer
    out << "    push ebp\n";
    out << "    mov ebp, esp\n";

    if (actualFrameSize > 0)
    {
        // reserve memory in stack for stack frame (align to 4 bytes)
        int alignedSize = (actualFrameSize + x86_32::STACK_ALIGNMENT_BIT_WISE) & ~x86_32::STACK_ALIGNMENT_BIT_WISE;
        out << "    sub esp, " << alignedSize << "\n";
    }
}

void X86_Emitter::EmitEpilogue(std::ostream& out)
{
    out << "    mov esp, ebp\n";
    out << "    pop ebp\n";
    out << "    ret\n";
}

void X86_Emitter::EmitInstruction(const IRInstruction* instruction, std::ostream& out)
{
    auto opcode = instruction->GetOpcode();

    const IRBaseValue* op1 = instruction->GetNumOperands() >= x86_common::SINGLE_OPERAND ? 
        instruction->GetOperand(x86_common::SINGLE_OPERAND_INDEX) : 
        nullptr;
    
    const IRBaseValue* op2 = instruction->GetNumOperands() >= x86_common::TWO_OPERANDS ? 
        instruction->GetOperand(x86_common::TWO_OPERANDS_INDEX) : 
        nullptr;

    const IRBaseValue* op3 = instruction->GetNumOperands() >= x86_common::THREE_OPERANDS ? 
        instruction->GetOperand(x86_common::THREE_OPERANDS_INDEX) : 
        nullptr;

    switch (opcode)
    {
        // -----------------------
        // Integer arithmetic
        // -----------------------
        case IROpcode::Add:
        case IROpcode::Sub:
        case IROpcode::Mul:
        case IROpcode::SDiv:
        case IROpcode::UDiv:
        case IROpcode::SRem:
        case IROpcode::URem:
        {
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";

            switch (opcode)
            {
                case IROpcode::Add:
                    out << "    add eax, " << this->GetOperandAsm(op2, out) << "\n";
                    break;

                case IROpcode::Sub:
                    out << "    sub eax, " << this->GetOperandAsm(op2, out) << "\n";
                    break;

                case IROpcode::Mul:
                    out << "    imul eax, " << this->GetOperandAsm(op2, out) << "\n";
                    break;

                case IROpcode::SDiv:
                    out << "    cdq\n";  // sign-extend EAX into EDX:EAX (32-bit)
                    out << "    mov ebx, " << this->GetOperandAsm(op2, out) << "\n";
                    out << "    idiv ebx\n";
                    break;

                case IROpcode::UDiv:
                    out << "    xor edx, edx\n";  // edx = 0 for unsigned
                    out << "    mov ebx, " << this->GetOperandAsm(op2, out) << "\n";
                    out << "    div ebx\n";
                    break;

                case IROpcode::SRem:
                    out << "    cdq\n";
                    out << "    mov ebx, " << this->GetOperandAsm(op2, out) << "\n";
                    out << "    idiv ebx\n";
                    out << "    mov eax, edx\n";  // remainder in edx
                    break;

                case IROpcode::URem:
                    out << "    xor edx, edx\n";
                    out << "    mov ebx, " << this->GetOperandAsm(op2, out) << "\n";
                    out << "    div ebx\n";
                    out << "    mov eax, edx\n";  // remainder in edx
                    break;

                default:
                    break;
            }

            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;
        }

        // -----------------------
        // Bitwise operations
        // -----------------------
        case IROpcode::And:
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    and eax, " << this->GetOperandAsm(op2, out) << "\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;

        case IROpcode::Or:
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    or eax, " << this->GetOperandAsm(op2, out) << "\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;

        case IROpcode::Xor:
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    xor eax, " << this->GetOperandAsm(op2, out) << "\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;

        case IROpcode::Shl:
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    mov ecx, " << this->GetOperandAsm(op2, out) << "\n";
            out << "    shl eax, cl\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;

        case IROpcode::LShr:
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    mov ecx, " << this->GetOperandAsm(op2, out) << "\n";
            out << "    shr eax, cl\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;

        case IROpcode::AShr:
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    mov ecx, " << this->GetOperandAsm(op2, out) << "\n";
            out << "    sar eax, cl\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;

        // -----------------------
        // Integer comparisons
        // -----------------------
        case IROpcode::ICmpEq:
        case IROpcode::ICmpNe:
        case IROpcode::ICmpSlt:
        case IROpcode::ICmpSle:
        case IROpcode::ICmpSgt:
        case IROpcode::ICmpSge:
        case IROpcode::ICmpUlt:
        case IROpcode::ICmpUle:
        case IROpcode::ICmpUgt:
        case IROpcode::ICmpUge:
        {
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    cmp eax, " << this->GetOperandAsm(op2, out) << "\n";

            const char* setInstr = GetSetccMnemonic(opcode);

            out << "    " << setInstr << " al\n";
            out << "    movzx eax, al\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;
        }

        // -----------------------
        // Floating-point arithmetic (SSE2)
        // -----------------------
        case IROpcode::FAdd:
        case IROpcode::FSub:
        case IROpcode::FMul:
        case IROpcode::FDiv:
        case IROpcode::FRem:
        {
            // load operands into XMM registers
            this->LoadOperandAsFloat(op1, "xmm0", out);
            this->LoadOperandAsFloat(op2, "xmm1", out);

            switch (opcode)
            {
                case IROpcode::FAdd:
                    out << "    addss xmm0, xmm1\n";
                    break;

                case IROpcode::FSub:
                    out << "    subss xmm0, xmm1\n";
                    break;

                case IROpcode::FMul:
                    out << "    mulss xmm0, xmm1\n";
                    break;

                case IROpcode::FDiv:
                    out << "    divss xmm0, xmm1\n";
                    break;

                case IROpcode::FRem:
                {
                    // a % b = a - floor(a/b) * b
                    // xmm0 = a, xmm1 = b
                    out << "    movss xmm2, xmm0\n";  // xmm2 = a (save original)
                    out << "    divss xmm0, xmm1\n";  // xmm0 = a / b
                    out << "    cvttss2si eax, xmm0\n";  // eax = truncate(a/b)
                    out << "    cvtsi2ss xmm0, eax\n";  // xmm0 = (float)truncate
                    out << "    mulss xmm0, xmm1\n";  // xmm0 = truncate * b
                    out << "    subss xmm2, xmm0\n";  // xmm2 = a - truncate*b
                    out << "    movss " << this->slotOfInstr(instruction) << ", xmm2\n";
                    break;
                }

                default:
                    break;
            }

            // store result
            if (opcode != IROpcode::FRem)
            {
                out << "    movss " << this->slotOfInstr(instruction) << ", xmm0\n";
            }
            break;
        }

        // -----------------------
        // Floating-point comparisons (SSE2)
        // -----------------------
        case IROpcode::FCmpEq:
        case IROpcode::FCmpNe:
        case IROpcode::FCmpLt:
        case IROpcode::FCmpLe:
        case IROpcode::FCmpGt:
        case IROpcode::FCmpGe:
        {
            // load operands into XMM registers
            this->LoadOperandAsFloat(op1, "xmm0", out);
            this->LoadOperandAsFloat(op2, "xmm1", out);

            // Compare xmm0 with xmm1 (sets EFLAGS)
            out << "    ucomiss xmm0, xmm1\n";

            const char* setInstr = GetSetccMnemonic(opcode);

            out << "    " << setInstr << " al\n";
            out << "    movzx eax, al\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;
        }

        // -----------------------
        // Memory operations
        // -----------------------
        case IROpcode::Load:
        {
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;
        }

        case IROpcode::Store:
        {
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    mov " << this->GetOperandAsm(op2, out) << ", eax\n";
            break;
        }

        case IROpcode::Alloca:
        {
            // allocate a new stack slot for a local variable
            int offset = m_nextVarStackOffset;
            m_nextVarStackOffset += x86_32::STACK_SLOT_SIZE;
            m_valueToStackOffset[instruction] = offset;
            break;
        }

        // -----------------------
        // Type conversion
        // -----------------------
        case IROpcode::FPToSI:
        {
            out << "    ; FPToSI: convert float to signed int\n";
            out << "    movss xmm0, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    cvttss2si eax, xmm0\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;
        }

        case IROpcode::SIToFP:
        {
            out << "    ; SIToFP: convert signed int to float\n";
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    cvtsi2ss xmm0, eax\n";
            out << "    movss " << this->slotOfInstr(instruction) << ", xmm0\n";
            break;
        }

        // -----------------------
        // Control flow
        // -----------------------
        case IROpcode::Br:
        {
            const auto& successors = instruction->GetParent()->GetSuccessors();
            out << "    jmp ." << successors[0]->GetLabel() << "\n";
            break;
        }

        case IROpcode::CondBr:
        {
            const auto& successors = instruction->GetParent()->GetSuccessors();
            out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            out << "    cmp eax, 0\n";
            out << "    jne ." << successors[0]->GetLabel() << "\n";
            out << "    jmp ." << successors[1]->GetLabel() << "\n";
            break;
        }

        case IROpcode::Ret:
            if (op1)
            {
                out << "    mov eax, " << this->GetOperandAsm(op1, out) << "\n";
            }
            out << "    jmp ." << this->m_currentFunc->GetName() << "_epilogue\n";
            break;

        case IROpcode::Call:
        {
            auto operands = instruction->GetOperands();
            int numOperands = static_cast<int>(operands.size());

            // 32-bit cdecl: push ALL arguments right to left
            for (int i = numOperands - 1; i >= 0; i--)
            {
                out << "    push dword " << this->GetOperandAsm(operands[i], out) << "\n";
            }

            std::string funcName = instruction->GetCalledFunction()->GetName();

            if (TargetArchitecture::GetOS() == OS::Windows)
            {
                out << "    call _" << funcName << "\n";
            }
            else
            {
                out << "    call " << funcName << "\n";
            }

            // caller cleans up stack in cdecl
            if (numOperands > 0)
            {
                out << "    add esp, " << (numOperands * x86_32::ARGUMENT_SIZE) << "\n";
            }

            // store return value
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;
        }

        case IROpcode::Select:
        {
            std::string lblTrue = this->SelectLabelGenerator();
            std::string lblEnd = this->SelectLabelGenerator();

            out << "    mov eax, " << GetOperandAsm(op1, out) << "\n";
            out << "    cmp eax, 0\n";
            out << "    jne " << lblTrue << "\n";
            // Condition false: use op3 (false value)
            out << "    mov eax, " << this->GetOperandAsm(op3, out) << "\n";
            out << "    jmp " << lblEnd << "\n";
            out << lblTrue << ":\n";
            // Condition true: use op2 (true value)
            out << "    mov eax, " << this->GetOperandAsm(op2, out) << "\n";
            out << lblEnd << ":\n";
            out << "    mov " << this->slotOfInstr(instruction) << ", eax\n";
            break;
        }

        default:
            out << "    ; Unhandled opcode\n";
            break;
    }
}

void X86_Emitter::EmitStart(std::ostream& out)
{
    switch (TargetArchitecture::GetOS())
    {
        case OS::Linux:
        {
            out << "_start:\n";
            out << "    call main\n";

            // exit syscall (sys_exit = 1)
            out << "    mov ebx, eax\n";  // exit code from main's return
            out << "    mov eax, 1\n";    // sys_exit syscall number
            out << "    int 0x80\n";      // interrupt to kernel

            // ---- Built-in: println(value: int) -> void ----
            // Minimal integer println using Linux write(1, buf, len)
            out << "\n";
            out << "println:\n";
            out << "    push ebp\n";
            out << "    mov ebp, esp\n";
            out << "    sub esp, 32\n";
            out << "    lea esi, [esp]\n";
            out << "    mov edi, esi\n";
            out << "    add esi, 20\n";
            out << "    mov byte [esi], 10\n";
            out << "    mov eax, [ebp+8]\n";
            out << "    cmp eax, 0\n";
            out << "    jne .Lconvert\n";
            out << "    dec esi\n";
            out << "    mov byte [esi], '0'\n";
            out << "    jmp .Lwrite\n";
            out << ".Lconvert:\n";
            out << "    xor edx, edx\n";
            out << ".Lloop:\n";
            out << "    xor edx, edx\n";
            out << "    mov ecx, 10\n";
            out << "    div ecx\n";
            out << "    dec esi\n";
            out << "    add dl, '0'\n";
            out << "    mov [esi], dl\n";
            out << "    test eax, eax\n";
            out << "    jnz .Lloop\n";
            out << ".Lwrite:\n";
            out << "    lea edx, [edi+21]\n";
            out << "    sub edx, esi\n";
            out << "    mov eax, 4\n";
            out << "    mov ebx, 1\n";
            out << "    mov ecx, esi\n";
            out << "    int 0x80\n";
            out << "    mov esp, ebp\n";
            out << "    pop ebp\n";
            out << "    ret\n";

            // ---- Built-in: println_bool(value: bool) -> void ----
            // Prints "true\n" or "false\n" via write(1, ...).
            out << "\n";
            out << "println_bool:\n";
            out << "    push ebp\n";
            out << "    mov ebp, esp\n";
            out << "    cmp dword [ebp+8], 0\n";
            out << "    je .Lbool_false\n";
            out << "    mov ecx, __println_bool_true\n";
            out << "    mov edx, 5\n";
            out << "    jmp .Lbool_write\n";
            out << ".Lbool_false:\n";
            out << "    mov ecx, __println_bool_false\n";
            out << "    mov edx, 6\n";
            out << ".Lbool_write:\n";
            out << "    mov eax, 4\n";
            out << "    mov ebx, 1\n";
            out << "    int 0x80\n";
            out << "    pop ebp\n";
            out << "    ret\n";
            break;
        }

        case OS::Windows:
        {
            out << "_mainCRTStartup:\n";
            out << "    call _main\n";

            // exit() flushes CRT stdio buffers
            out << "    push eax\n";
            out << "    call _exit\n";
            out << "    add esp, 4\n";

            // Halt if exit returns (should not)
            out << "    push eax\n";            // push exit code
            out << "    call _ExitProcess@4\n"; // stdcall: callee cleans stack

            // ---- Built-in: println(value: int) -> void ----
            // Wraps printf with a "%d\n" format string (cdecl).
            out << "\n";
            out << "_println:\n";
            out << "    push ebp\n";
            out << "    mov ebp, esp\n";
            out << "    push dword [ebp+8]\n";  // arg: value
            out << "    push __println_fmt_int\n"; // arg: fmt
            out << "    call _printf\n";
            out << "    add esp, 8\n"; // clean up 2 args
            out << "    pop ebp\n";
            out << "    ret\n";

            // ---- Built-in: println_double(value: float bits) -> void ----
            // Convert 32-bit float to 64-bit double for printf %g (cdecl).
            out << "\n";
            out << "_println_double:\n";
            out << "    push ebp\n";
            out << "    mov ebp, esp\n";
            out << "    movss xmm0, dword [ebp+8]\n";   // load 32-bit float
            out << "    cvtss2sd xmm0, xmm0\n";  // widen to double
            out << "    sub esp, 8\n";
            out << "    movsd qword [esp], xmm0\n";  // push double (8 bytes)
            out << "    push __println_fmt_double\n";  // push fmt
            out << "    call _printf\n";
            out << "    add esp, 12\n";  // clean up (4 fmt + 8 double)
            out << "    pop ebp\n";
            out << "    ret\n";

            // ---- Built-in: println_str(ptr: char*) -> void ----
            out << "\n";
            out << "_println_str:\n";
            out << "    push ebp\n";
            out << "    mov ebp, esp\n";
            out << "    push dword [ebp+8]\n";           // arg: string ptr
            out << "    push __println_fmt_str\n";        // arg: fmt
            out << "    call _printf\n";
            out << "    add esp, 8\n";
            out << "    pop ebp\n";
            out << "    ret\n";

            // ---- Built-in: println_bool(value: bool) -> void ----
            // Prints "true" or "false" via printf("%s\n", ...).
            out << "\n";
            out << "_println_bool:\n";
            out << "    push ebp\n";
            out << "    mov ebp, esp\n";
            out << "    cmp dword [ebp+8], 0\n";
            out << "    je ._println_bool_false\n";
            out << "    push __println_bool_true\n";
            out << "    jmp ._println_bool_out\n";
            out << "._println_bool_false:\n";
            out << "    push __println_bool_false\n";
            out << "._println_bool_out:\n";
            out << "    push __println_fmt_str\n";
            out << "    call _printf\n";
            out << "    add esp, 8\n";
            out << "    pop ebp\n";
            out << "    ret\n";
            break;
        }

        default:
            break;
    }
}

std::string X86_Emitter::GetGlobalDirective(const std::string& symbol) const
{
    switch (TargetArchitecture::GetOS())
    {
        case OS::Linux:
            return "global " + symbol + "\n";

        case OS::Windows:
            return "global _" + symbol + "\n";

        default:
            return "global " + symbol + "\n";
    }
}

std::string X86_Emitter::GetOperandAsm(const IRBaseValue* operand, std::ostream& out)
{
    if (!operand)
    {
        return "0";
    }

    if (auto* intLiteral = dynamic_cast<const IRConstantInt*>(operand))
    {
        return std::to_string(intLiteral->GetValue());
    }

    if (auto* floatLiteral = dynamic_cast<const IRConstantFloat*>(operand))
    {
        // case already stored, just return the slot
        auto it = this->m_valueToStackOffset.find(floatLiteral);
        if (it != this->m_valueToStackOffset.end())
        {
            return "dword [ebp-" + std::to_string(it->second) + "]";
        }

        // allocate a slot and write the constant there
        std::string slot = this->slotOfInstr(floatLiteral);

        float value = static_cast<float>(floatLiteral->GetValue());
        uint32_t bits = 0;
        std::memcpy(&bits, &value, sizeof(float));

        // store as 32-bit hex value
        out << "    mov dword " << slot << ", 0x" << std::hex << bits << std::dec << "\n";
        return slot;
    }

    if (auto* strConst = dynamic_cast<const IRConstantString*>(operand))
    {
        // return the label of the string constant in the .data section
        if (TargetArchitecture::GetOS() == OS::Windows)
        {
            return strConst->GetLabel();
        }
        else
        {
            return strConst->GetLabel();
        }
    }

    if (auto* boolLiteral = dynamic_cast<const IRConstantBool*>(operand))
    {
        return boolLiteral->GetValue() ? "1" : "0";
    }

    if (auto* globalVar = dynamic_cast<const IRGlobalVariable*>(operand))
    {
        if (TargetArchitecture::GetOS() == OS::Windows)
        {
            return "dword [_" + globalVar->GetName() + "]";
        }
        else
        {
            return "dword [" + globalVar->GetName() + "]";
        }
    }

    // operand is a function argument
    // 32-bit cdecl: all arguments on stack
    // [ebp+8] = arg0, [ebp+12] = arg1, etc.
    if (auto* arg = dynamic_cast<const IRArgument*>(operand))
    {
        size_t argIndex = arg->GetIndex();
        int offset = x86_32::BASE_OFFSET + (static_cast<int>(argIndex) * x86_32::ARGUMENT_SIZE);
        return "dword [ebp+" + std::to_string(offset) + "]";
    }

    // otherwise it's a local variable or temporary
    return slotOfInstr(operand);
}

std::string X86_Emitter::slotOfInstr(const IRBaseValue* value)
{
    if (!value)
    {
        return "";
    }

    // check if already assigned a stack slot
    auto it = this->m_valueToStackOffset.find(value);
    if (it != this->m_valueToStackOffset.end())
    {
        return "dword [ebp-" + std::to_string(it->second) + "]";
    }

    // allocate new stack slot for this temporary
    int offset = this->m_nextTempStackOffset;
    this->m_nextTempStackOffset += x86_32::STACK_SLOT_SIZE;
    this->m_valueToStackOffset[value] = offset;

    return "dword [ebp-" + std::to_string(offset) + "]";
}

void X86_Emitter::LoadOperandAsFloat(const IRBaseValue* operand, const std::string& xmmReg, std::ostream& out)
{
    // integer constant - convert to float
    if (auto* intConst = dynamic_cast<const IRConstantInt*>(operand))
    {
        // push integer to stack, then convert to float via SSE
        out << "    push dword " << intConst->GetValue() << "\n";
        out << "    cvtsi2ss " << xmmReg << ", dword [esp]\n";
        out << "    add esp, 4\n";
        return;
    }

    if (auto* floatConst = dynamic_cast<const IRConstantFloat*>(operand))
    {
        float value = static_cast<float>(floatConst->GetValue());
        uint32_t bits = 0;
        std::memcpy(&bits, &value, sizeof(float));

        out << "    push dword 0x" << std::hex << bits << std::dec << "\n";
        out << "    movss " << xmmReg << ", dword [esp]\n";
        out << "    add esp, 4\n";
        return;
    }

    // memory operand (variable or temporary)
    std::string slot = this->GetOperandAsm(operand, out);
    out << "    movss " << xmmReg << ", " << slot << "\n";
}
