void X86_Emitter::EmitStart(std::ostream &out)
{
    switch (TargetArchitecture::GetOS())
    {
        case OS::Linux:
        {
            out << "_start:\n";
            out << "    call main\n";

            // exit  (main return)
            out << "    mov ebx, eax\n";  // set exist code
            out << "    mov eax, 1\n";  // save sys_exit

            // Syscall interrupt, teminate program
            out << "    int 0x80\n";
            break;
        }
        
        case OS::Windows:
        {
            out << "_start:\n";
            out << "    call _main\n";
            
            out << "    push eax\n";  // set return value of _main as argument for exist
            out << "    call _ExitProcess@4\n";  // stdcall decoration
            break;
        }
        
        default:
            break;
    }
}

std::string X86_Emitter::GetSectionDirective(SectionType sectionType)
{
    switch (sectionType)
    {
        case SectionType::TEXT:
            return "section .text\n";

        case SectionType::DATA:
            return "section .data\n";

        case SectionType::RODATA:
            // NASM uses .rdata on Windows, .rodata on ELF
            return (TargetArchitecture::GetOS() == OS::Windows) ? 
                "section .rdata\n" :
                "section .rodata\n";

        case SectionType::BSS:
            return "section .bss\n";
        
        default:
            return "";
    }
}

