std::string X86_Emitter::EmitHeader()
{
    std::ostringstream header;
    
    // picoC signature
    header << "; Generated by picoC compiler\n";

    switch (TargetArchitecture::GetOS())
    {
        case OS::Linux:
            header << "; Target: x86 Linux (32-bit)\n\n";
            header << "BITS 32\n\n";
            break;
        
        case OS::Windows:
            header << "; Target: x86 Windows (32-bit)\n\n";
            header << "BITS 32\n\n";
            header << "extern _ExitProcess@4\n\n";

        default:
            break;
    }

    return header.str();
}

void X86_Emitter::EmitPrologue(const IRFunction *func, int frameSize, std::ostream &out)
{
    // save caller at stack
    out << "    push ebp\n";
    out << "    mov ebp, esp\n";

    if (frameSize > 0)
    {
        // reserve memory in stack for stack frame
        int alignedSize = (frameSize + 3) & ~3;
        out << "    sub esp, " << std::to_string(alignedSize) << "\n";
    }
}

void X86_Emitter::EmitEpilogue(std::ostream &out)
{
    out << "    mov esp, ebp\n";  // Undo frame allocation.
    out << "    pop ebp\n";  // Restore old base pointer.
    out << "    ret\n";  // Return from function.

    this->m_currentFunc = nullptr;
}

